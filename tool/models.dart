/// Writes lib/src/ai/models.generated.dart from catalog/*.json, pi's model catalog for the providers chorus serves.
///
///     dart run tool/models.dart
library;

import 'dart:convert';
import 'dart:io';

const providers = ['anthropic', 'google', 'openai'];

void main() {
  final out = StringBuffer()
    ..writeln('// Generated by tool/models.dart from catalog/*.json (pi\'s model catalog). Do not edit: run')
    ..writeln('// `dart run tool/models.dart`.')
    ..writeln()
    ..writeln("import 'model.dart';")
    ..writeln()
    ..writeln("/// pi's built-in chat models, by provider and id; read through `getBuiltinModel` and the others.")
    ..writeln('const builtinCatalog = <String, Map<String, Model>>{');
  for (final provider in providers) {
    final models = jsonDecode(File('catalog/$provider.json').readAsStringSync()) as Map<String, Object?>;
    out.writeln('  ${_literal(provider)}: {');
    for (final MapEntry(:key, :value) in models.entries) {
      out.writeln('    ${_literal(key)}: ${_model(value as Map<String, Object?>)},');
    }

    out.writeln('  },');
  }

  out.writeln('};');
  File('lib/src/ai/models.generated.dart').writeAsStringSync(out.toString());
  Process.runSync('dart', ['format', 'lib/src/ai/models.generated.dart']);
}

// A Model constructor call for one catalog entry.
String _model(Map<String, Object?> m) {
  final cost = m['cost'] as Map<String, Object?>;
  final fields = {
    'id': m['id'],
    'name': m['name'],
    'api': m['api'],
    'provider': m['provider'],
    'baseUrl': m['baseUrl'],
    'input': m['input'],
    'reasoning': m['reasoning'] ?? false,
    'levels': m['thinkingLevelMap'],
    'contextWindow': m['contextWindow'],
    'maxTokens': m['maxTokens'],
    'compat': m['compat'],
  };
  final args = [
    for (final MapEntry(:key, :value) in fields.entries)
      if (value != null) '$key: ${_literal(value)}',
    'cost: ${_cost(cost)}',
    if (m['headers'] != null) 'headers: ${_literal(m['headers'])}',
    if (m['promptCache'] case final Map<String, Object?> cache) 'promptCache: ${_object('PromptCache', cache)}',
    if (m['inputLimits'] case final Map<String, Object?> limits) 'inputLimits: ${_limits(limits)}',
  ];
  return 'Model(${args.join(', ')})';
}

String _cost(Map<String, Object?> c) {
  final tiers = [
    for (final t in (c['tiers'] as List<Object?>? ?? const []).cast<Map<String, Object?>>())
      'Tier(above: ${t['inputTokensAbove']}, ${_rates(t)})',
  ];
  return 'ModelCost(${_rates(c)}${tiers.isEmpty ? '' : ', tiers: [${tiers.join(', ')}]'})';
}

String _limits(Map<String, Object?> l) {
  final images = l['images'] as Map<String, Object?>?;
  final resize = images?['resize'] as Map<String, Object?>?;
  final imageArgs = {...?images, if (resize != null) 'resize': _Code(_object('ImageResize', resize))};
  return _object('InputLimits', {
    'maxRequestBytes': ?l['maxRequestBytes'],
    if (images != null) 'images': _Code(_object('ImageLimits', imageArgs)),
  });
}

// A constructor call with named arguments.
String _object(String type, Map<String, Object?> args) => '$type(${args.entries.map(_argument).join(', ')})';

// A named argument: a value as a literal, _Code as it is.
String _argument(MapEntry<String, Object?> arg) {
  final value = arg.value;
  return '${arg.key}: ${value is _Code ? value.code : _literal(value)}';
}

/// Dart code to write as it is.
class _Code {
  const _Code(this.code);

  final String code;
}

String _rates(Map<String, Object?> r) {
  return [
    for (final k in ['input', 'output', 'cacheRead', 'cacheWrite']) '$k: ${_double(r[k] as num)}',
  ].join(', ');
}

String _double(num n) => n is int ? '$n.0' : '$n';

// A JSON value as a Dart literal.
String _literal(Object? value) {
  return switch (value) {
    null => 'null',
    String() =>
      "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$').replaceAll('\n', r'\n')}'",
    num() || bool() => '$value',
    List() => '[${value.map(_literal).join(', ')}]',
    Map() => '{${value.entries.map((e) => '${_literal(e.key)}: ${_literal(e.value)}').join(', ')}}',
    _ => throw ArgumentError('Not JSON: $value'),
  };
}
